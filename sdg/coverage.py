"""Count how often every scenario appears across all scene specs, and fail if any planned case is missing.

    uv run python -m sdg.coverage            # writes docs/SDG_COVERAGE.md

Counts come from the specs themselves (the exact scenes that will be rendered), not from the config.
"""

from __future__ import annotations

import collections
import itertools
import sys

from sdg.scene_sampler import REPO, Inputs, chunk_range, n_chunks, sample_scene

OUT = REPO / "docs" / "SDG_COVERAGE.md"
MIN_PER_CASE = {"product_combo": 50, "part_step": 50, "defect_part": 10, "build_state_product": 20, "trap_family": 20}


def all_specs(inputs: Inputs, sets=("A", "B", "C", "D")):
    for s in sets:
        for c in range(n_chunks(inputs, s)):
            for i in chunk_range(inputs, s, c):
                yield sample_scene(inputs, s, i)


def count(specs, inputs: Inputs) -> dict[str, collections.Counter]:
    c = {k: collections.Counter() for k in (
        "scenes_per_set", "product_combo", "part_step", "defect_type", "defect_part", "build_state_product",
        "trap_family", "foreign", "wrist_target", "arm_mode", "cluster_like", "rejects", "spares")}
    for spec in specs:
        s = spec["set"]
        c["scenes_per_set"][s] += 1
        c["product_combo"][tuple(spec["products"])] += 1
        for p, step in spec["assembly_step"].items():
            c["part_step"][(int(p), step)] += 1
        for o in spec["objects"]:
            if o["variant"] != "ok":
                c["defect_type"][o["variant"]] += 1
                c["defect_part"][(o["object_id"], o["variant"])] += 1
            if o["build_state"] and s == "D":
                c["build_state_product"][(o["product"], o["build_state"])] += 1
            if o["kind"] == "trap":
                c["trap_family"][inputs.taxonomy[o["object_id"]]["family"]] += 1
            if o["kind"] == "foreign":
                c["foreign"][o["foreign_type"]] += 1
        c["arm_mode"][(s, spec["arm"]["mode"])] += 1
        c["rejects"][sum(o["kind"] == "reject" for o in spec["objects"])] += 1
        c["spares"][sum(o["kind"] == "spare" for o in spec["objects"])] += 1
        if "wrist_target_uid" in spec:
            t = next(o for o in spec["objects"] if o["uid"] == spec["wrist_target_uid"])
            c["wrist_target"][(s, t["object_id"])] += 1
    return c


def missing_cases(c: dict, inputs: Inputs) -> list[str]:
    parts = sorted(k for k in inputs.geometry if k.startswith("M"))
    expected = {
        "product_combo": list(itertools.combinations(range(1, 7), 3)),
        "part_step": [(p, s) for p in range(1, 7) for s in range(5)],
        "defect_part": [(p, d) for p in parts for d in inputs.sets["defaults"]["defect_types"]],
        "build_state_product": [(p, b) for p in range(1, 7) for b in inputs.sets["sets"]["D"]["build_states"]],
        "trap_family": sorted({inputs.taxonomy[p]["family"] for p in parts}),
    }
    return [f"{key} {case}: {c[key][case]} < {MIN_PER_CASE[key]}"
            for key, cases in expected.items() for case in cases if c[key][case] < MIN_PER_CASE[key]]


def _table(title: str, counter: collections.Counter, fmt=str) -> str:
    rows = "\n".join(f"| {fmt(k)} | {v:,} |" for k, v in sorted(counter.items(), key=lambda kv: str(kv[0])))
    return f"### {title}\n\n| Case | Scenes / objects |\n|---|---|\n{rows}\n"


def report(c: dict, missing: list[str]) -> str:
    lo = lambda key: min(c[key].values())
    head = (f"# Synthetic data coverage\n\nGenerated by `uv run python -m sdg.coverage` from all scene specs "
            f"({sum(c['scenes_per_set'].values()):,} scenes). Minimum counts required per case: {MIN_PER_CASE}.\n\n"
            f"**Missing or thin cases: {len(missing)}**" + ("" if not missing else "\n\n- " + "\n- ".join(missing))
            + f"\n\n| Check | Smallest count |\n|---|---|\n| 3-product combination (20) | {lo('product_combo')} |\n"
            f"| product x assembly step (30) | {lo('part_step')} |\n| part x defect type (144) | {lo('defect_part')} |\n"
            f"| product x build state (24) | {lo('build_state_product')} |\n| look-alike trap family | {lo('trap_family')} |\n")
    sections = [
        _table("Scenes per set", c["scenes_per_set"]),
        _table("Defect types (all sets)", c["defect_type"]),
        _table("Build states per product (set D)", c["build_state_product"], lambda k: f"product {k[0]} · {k[1]}"),
        _table("Look-alike traps by family", c["trap_family"]),
        _table("Foreign objects", c["foreign"]),
        _table("Arm pose per set", c["arm_mode"], lambda k: f"{k[0]} · {k[1]}"),
        _table("Rejects in tray per scene", c["rejects"]),
        _table("Spares in store per scene", c["spares"]),
        _table("Products x assembly step", c["part_step"], lambda k: f"product {k[0]} · step {k[1]}"),
        _table("3-product combinations", c["product_combo"], lambda k: " + ".join(map(str, k))),
    ]
    return head + "\n" + "\n".join(sections)


def main() -> None:
    inputs = Inputs.load()
    c = count(all_specs(inputs), inputs)
    missing = missing_cases(c, inputs)
    OUT.write_text(report(c, missing))
    print(f"wrote {OUT.relative_to(REPO)}; missing/thin cases: {len(missing)}")
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
