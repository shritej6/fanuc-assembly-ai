"""Summarize raw seating runs into seating_results.yaml and check limits.yaml against them.
Authored by Shritej Gunda.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ALLOWED = ("aligned", "offset_x_0.5")     # inside every part's 0.5 mm clearance: what the skills must achieve


def load(paths: list[str]) -> list[dict]:
    rows = []
    for p in paths:
        rows += [json.loads(line) for line in Path(p).read_text().splitlines() if line.strip()]
    return rows


def condition_summary(runs: list[dict]) -> dict:
    runs = sorted(runs, key=lambda r: -r["cap_N"])
    seated = [r for r in runs if r["seated"]]
    top = runs[0]
    seated_caps = [r["cap_N"] for r in seated]
    sink_caps = [r["cap_N"] for r in runs if not r["seated"] and seated_caps and r["cap_N"] > max(seated_caps)]
    return {"min_cap_seated_N": min(seated_caps) if seated_caps else None,
            "max_cap_seated_N": max(seated_caps) if seated_caps else None,
            "press_sink_cap_N": min(sink_caps) if sink_caps else None,
            "seated_at_15N": top["seated"], "final_dz_mm_at_15N": top["final_dz_mm"],
            "final_xy_err_mm_at_15N": top["final_xy_err_mm"],
            "pre_seat_peak_axial_N": top["pre_seat_peak_axial_N"],
            "pre_seat_peak_lateral_N": top["pre_seat_peak_lateral_N"],
            "pre_seat_peak_torque_Nm": top["pre_seat_peak_torque_Nm"],
            "press_peak_axial_N": top["peak_axial_N"], "press_peak_lateral_N": top["peak_lateral_N"],
            "press_peak_torque_Nm": top["peak_torque_Nm"]}


def summarize(rows: list[dict]) -> dict:
    grouped = defaultdict(lambda: defaultdict(list))
    for r in rows:
        grouped[r["pair"]][r["condition"]].append(r)
    return {pair: {c: condition_summary(runs) for c, runs in conds.items()} for pair, conds in sorted(grouped.items())}


def check(table: dict, limits: dict) -> dict:
    """Which allowed-condition results break a limit, and the largest measured seating force."""
    worst_seat, breaks = 0.0, []
    sf = limits["method"]["safety_factor_min"]
    for pair, conds in table.items():
        axial = limits.get("per_part_axial_N", {}).get(pair.split("_onto_")[0], {}).get("axial_N", limits["axial_N"])
        for c in ALLOWED:
            s = conds.get(c)
            if s is None:
                continue
            if s["min_cap_seated_N"] is None:
                breaks.append(f"{pair} {c}: does not seat at 15 N")
                continue
            worst_seat = max(worst_seat, s["min_cap_seated_N"])
            if s["min_cap_seated_N"] > axial:
                breaks.append(f"{pair} {c}: needs {s['min_cap_seated_N']} N > axial limit {axial}")
            if s["press_sink_cap_N"] is not None and axial * sf > s["press_sink_cap_N"]:
                breaks.append(f"{pair} {c}: sinks past the seat at {s['press_sink_cap_N']} N < {sf} x axial {axial}")
            if s["pre_seat_peak_lateral_N"] > limits["lateral_N"]:
                breaks.append(f"{pair} {c}: lateral {s['pre_seat_peak_lateral_N']} N > {limits['lateral_N']}")
            if s["pre_seat_peak_torque_Nm"] > limits["torque_Nm"]:
                breaks.append(f"{pair} {c}: torque {s['pre_seat_peak_torque_Nm']} > {limits['torque_Nm']}")
    return {"max_min_cap_seated_N_allowed_conditions": worst_seat,
            "axial_limit_covers_seating": limits["axial_N"] >= worst_seat, "violations": breaks}


def main(paths: list[str]) -> None:
    rows = load(paths)
    table = summarize(rows)
    limits = yaml.safe_load((HERE / "limits.yaml").read_text())
    doc = {"status": "SIM_MEASURED",
           "source": "sim/assembly_lab/physics/measure_seating.py (Isaac Sim 6.0 PhysX, SDF colliders, contact.yaml); "
                     f"{len(rows)} runs",
           "model_assumptions": ["rubber-pad lateral compliance 2 N/mm (not measured)",
                                 "stiff wrist: tilt held, no levelling (the skill levels out; tilt rows are worst case)",
                                 "receivers fixed (the real base is free-standing, 29.5 g)",
                                 "PLA friction 0.35 / 0.30 (estimate, contact.yaml)"],
           "allowed_conditions": list(ALLOWED), "check_against_limits": check(table, limits), "pairs": table}
    (HERE / "seating_results.yaml").write_text("# GENERATED by summarize_seating.py\n"
                                               + yaml.safe_dump(doc, sort_keys=False, width=120))
    print(json.dumps(doc["check_against_limits"], indent=1))


if __name__ == "__main__":
    main(sys.argv[1:])
